-- Dnevnik sprememb opreme (avtomatski vnosi v kartoteki) in kupec pri prodaji.
--
-- Vsako spremembo zapišejo triggerji v bazi (ne aplikacija), zato se zabeleži vse - tudi spremembe
-- iz SQL Editorja ali drugih orodij. Dnevnik se ne da urejati ali brisati (RLS: samo branje);
-- zapise doda samo funkcija rbo_dnevnik_zapisi (security definer).
--
-- Kaj se beleži:
--   rbo_oprema         dodana v sistem, vsak spremenjen podatek (iz A v B), izbris
--   rbo_prodaja        vsak spremenjen podatek prodaje (status, kupec, cena ...), nova prodaja
--   rbo_slike          dodana / zamenjana / odstranjena slika
--   rbo_tehnicni_list  ustvarjen, spremenjen podatek, izbrisan
--   rbo_kartoteka      izbrisan ročni zapis (ročni zapisi ostanejo v rbo_kartoteka)

-- 1) Kupec pri prodaji
alter table public.rbo_prodaja add column if not exists kupec text;

-- 2) Tabela dnevnika
create table if not exists public.rbo_dnevnik (
    id         bigint generated by default as identity primary key,
    id_oprema  bigint not null references public.rbo_oprema (id) on delete cascade,
    cas        timestamptz not null default now(),
    uporabnik  text,                      -- e-mail prijavljenega uporabnika (null = sistem / SQL)
    sklop      text not null,             -- Oprema, Prodaja, Slike, Tehnični list, Kartoteka
    besedilo   text not null,             -- celoten zapis v berljivi obliki (PDF, Teams)
    spremembe  jsonb                      -- [{"oznaka": "Status prodaje", "staro": "...", "novo": "..."}]
);

create index if not exists rbo_dnevnik_oprema_idx on public.rbo_dnevnik (id_oprema, cas desc);

alter table public.rbo_dnevnik enable row level security;
drop policy if exists "fines beri" on public.rbo_dnevnik;
create policy "fines beri" on public.rbo_dnevnik for select to authenticated using (public.rbo_je_fines_uporabnik());
-- brez pravil za insert / update / delete: piše samo trigger

-- 3) Oznake polj (vrstni red = vrstni red na obrazcu)
create or replace function public.rbo_dnevnik_polja(tabela text)
returns text[][]
language sql
immutable
as $$
    select case tabela
        when 'rbo_oprema' then array[
            ['oprema_naziv', 'Naziv opreme'], ['koda', 'Ident (koda)'], ['serijska_stevilka', 'Serijska številka'],
            ['skupina_opreme', 'Skupina opreme'], ['leto_proizvodnje', 'Leto proizvodnje'],
            ['datum_prejema', 'Datum prejema'], ['kolicina', 'Količina'], ['em', 'EM'],
            ['ocena', 'Ocena stanja'], ['lastnistvo', 'Lastništvo'], ['skladisce', 'Skladišče'], ['komentar', 'Komentar']]
        when 'rbo_prodaja' then array[
            ['status_prodaje', 'Status prodaje'], ['imenovani_prodajalec', 'Imenovani prodajalec'],
            ['garancijski_rok_meseci', 'Garancija'], ['cena_nove', 'Cena nove'], ['rabat_procent', 'Rabat'],
            ['prodajna_cena', 'Prodajna cena'], ['datum_prodaje', 'Datum prodaje'], ['kupec', 'Kupec'],
            ['komentar_ob_prodaji', 'Komentar ob prodaji']]
        when 'rbo_tehnicni_list' then array[
            ['tip_opreme', 'Tip opreme'], ['naziv', 'Naziv'], ['leto_izdelave', 'Leto izdelave'],
            ['serijska', 'Serijska številka'], ['dimenzija', 'Dimenzija'], ['teza', 'Teža'],
            ['delovne_ure', 'Delovne ure'], ['prikljucna_moc', 'Priključna moč'],
            ['elektricni_priklop', 'Električni priklop'], ['varovalke', 'Varovalke'], ['temperatura', 'Temperatura'],
            ['priklop_vode', 'Priklop vode'], ['odvod_pare', 'Odvod pare'],
            ['kapaciteta_pekacev', 'Kapaciteta pekačev'], ['razdalja_med_pekaci', 'Razdalja med pekači'],
            ['opis', 'Opis']]
    end
$$;

-- 4) Vrednost za prikaz (datumi dd.mm.llll, zneski z vejico in €, ocena z opisom); prazno = null
create or replace function public.rbo_dnevnik_vrednost(polje text, v jsonb)
returns text
language plpgsql
immutable
as $$
declare
    t text := v #>> '{}';
begin
    if t is null or btrim(t) = '' then return null; end if;
    case
        when polje in ('datum_prejema', 'datum_prodaje') then
            return to_char(t::date, 'DD.MM.YYYY');
        when polje in ('cena_nove', 'prodajna_cena') then
            return replace(to_char(t::numeric, 'FM9999999990.00'), '.', ',') || ' €';
        when polje = 'rabat_procent' then
            return replace(trim(trailing '.' from trim(trailing '0' from to_char(t::numeric, 'FM9999990.00'))), '.', ',') || ' %';
        when polje = 'garancijski_rok_meseci' then
            return case when t::int = 0 then 'brez garancije' else t || ' mesecev' end;
        when polje = 'ocena' then
            return t || ' - ' || case t::int
                when 1 then 'Uničeno, neuporabno, neurejeno'
                when 2 then 'Zelo rabljeno'
                when 3 then 'Vidno rabljeno'
                when 4 then 'Očiščeno, skoraj novo, malo rabljeno'
                when 5 then 'Kot novo'
                else '' end;
        else
            return t;
    end case;
end
$$;

-- 5) Razlike med staro in novo vrstico: [{oznaka, staro, novo}] za vsa spremenjena polja
create or replace function public.rbo_dnevnik_razlike(tabela text, staro jsonb, novo jsonb)
returns jsonb
language plpgsql
immutable
as $$
declare
    p text[];
    a text;
    b text;
    rezultat jsonb := '[]'::jsonb;
begin
    foreach p slice 1 in array public.rbo_dnevnik_polja(tabela) loop
        a := public.rbo_dnevnik_vrednost(p[1], coalesce(staro -> p[1], 'null'::jsonb));
        b := public.rbo_dnevnik_vrednost(p[1], coalesce(novo -> p[1], 'null'::jsonb));
        if a is distinct from b then
            rezultat := rezultat || jsonb_build_object('oznaka', p[2], 'staro', a, 'novo', b);
        end if;
    end loop;
    return rezultat;
end
$$;

-- 6) Besedilo iz razlik: Podatek »X« se je spremenil iz »A« v »B«.
create or replace function public.rbo_dnevnik_besedilo(spremembe jsonb)
returns text
language sql
immutable
as $$
    select string_agg(
        format('%s se je spremenil iz »%s« v »%s«.',
            s ->> 'oznaka', coalesce(s ->> 'staro', '(prazno)'), coalesce(s ->> 'novo', '(prazno)')),
        E'\n' order by i)
    from jsonb_array_elements(spremembe) with ordinality as x(s, i)
$$;

-- 7) Zapis v dnevnik (edino mesto, ki piše v rbo_dnevnik)
create or replace function public.rbo_dnevnik_zapisi(p_id_oprema bigint, p_sklop text, p_besedilo text, p_spremembe jsonb default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
    if p_id_oprema is null or p_besedilo is null then return; end if;
    insert into public.rbo_dnevnik (id_oprema, uporabnik, sklop, besedilo, spremembe)
    values (p_id_oprema, nullif(auth.jwt() ->> 'email', ''), p_sklop, p_besedilo, p_spremembe);
end
$$;

revoke execute on function public.rbo_dnevnik_zapisi(bigint, text, text, jsonb) from public, anon, authenticated;

-- 8) Triggerji

-- 8a) Oprema
create or replace function public.rbo_dnevnik_oprema()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    r jsonb;
begin
    if tg_op = 'INSERT' then
        perform public.rbo_dnevnik_zapisi(new.id, 'Oprema',
            'Oprema je bila dodana v sistem na dan: ' || to_char(now() at time zone 'Europe/Ljubljana', 'DD.MM.YYYY') || '.');
        return new;
    end if;

    if old.visible and not new.visible then
        perform public.rbo_dnevnik_zapisi(new.id, 'Oprema', 'Oprema je bila izbrisana (skrita v aplikaciji).');
    elsif not old.visible and new.visible then
        perform public.rbo_dnevnik_zapisi(new.id, 'Oprema', 'Oprema je bila obnovljena (spet vidna v aplikaciji).');
    end if;

    r := public.rbo_dnevnik_razlike('rbo_oprema', to_jsonb(old), to_jsonb(new));
    if jsonb_array_length(r) > 0 then
        perform public.rbo_dnevnik_zapisi(new.id, 'Oprema', public.rbo_dnevnik_besedilo(r), r);
    end if;
    return new;
end
$$;

drop trigger if exists rbo_dnevnik_oprema on public.rbo_oprema;
create trigger rbo_dnevnik_oprema after insert or update on public.rbo_oprema
    for each row execute function public.rbo_dnevnik_oprema();

-- 8b) Prodaja: nova prodaja se zabeleži ob povezavi z opremo (ln_rbo_oprema_prodaja), sprememba ob update
create or replace function public.rbo_dnevnik_prodaja()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    r jsonb;
    o bigint;
begin
    if old.visible is distinct from new.visible then
        return new; -- prodaja se skrije skupaj z opremo (zabeleženo pri opremi)
    end if;
    r := public.rbo_dnevnik_razlike('rbo_prodaja', to_jsonb(old), to_jsonb(new));
    if jsonb_array_length(r) = 0 then return new; end if;
    for o in select id_oprema from public.ln_rbo_oprema_prodaja where id_prodaja = new.id_prodaja loop
        perform public.rbo_dnevnik_zapisi(o, 'Prodaja', public.rbo_dnevnik_besedilo(r), r);
    end loop;
    return new;
end
$$;

drop trigger if exists rbo_dnevnik_prodaja on public.rbo_prodaja;
create trigger rbo_dnevnik_prodaja after update on public.rbo_prodaja
    for each row execute function public.rbo_dnevnik_prodaja();

create or replace function public.rbo_dnevnik_prodaja_povezava()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    r jsonb;
begin
    select public.rbo_dnevnik_razlike('rbo_prodaja', '{}'::jsonb, to_jsonb(p))
    into r
    from public.rbo_prodaja p
    where p.id_prodaja = new.id_prodaja;
    if r is not null and jsonb_array_length(r) > 0 then
        perform public.rbo_dnevnik_zapisi(new.id_oprema, 'Prodaja', public.rbo_dnevnik_besedilo(r), r);
    end if;
    return new;
end
$$;

drop trigger if exists rbo_dnevnik_prodaja_povezava on public.ln_rbo_oprema_prodaja;
create trigger rbo_dnevnik_prodaja_povezava after insert on public.ln_rbo_oprema_prodaja
    for each row execute function public.rbo_dnevnik_prodaja_povezava();

-- 8c) Slike (zamenjava slike = upsert na isto mesto = update)
create or replace function public.rbo_dnevnik_slika_ime(vrsta text)
returns text
language sql
immutable
as $$
    select case
        when vrsta = 'Predstavna' then 'predstavna slika'
        when vrsta = 'Krmiljenje' then 'slika krmiljenja'
        when vrsta like 'Slika_' then 'slika ' || right(vrsta, 1)
        else vrsta
    end
$$;

create or replace function public.rbo_dnevnik_slike()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    ime text := public.rbo_dnevnik_slika_ime(coalesce(new.vrsta_slike, old.vrsta_slike));
begin
    if tg_op = 'INSERT' then
        perform public.rbo_dnevnik_zapisi(new.id_oprema, 'Slike', format('Dodana je bila %s.', ime));
    elsif tg_op = 'UPDATE' then
        perform public.rbo_dnevnik_zapisi(new.id_oprema, 'Slike', format('Zamenjana je bila %s.', ime));
    else
        -- ob izbrisu opreme iz baze (cascade) opreme ni več: zapisa ne dodamo
        if exists (select 1 from public.rbo_oprema where id = old.id_oprema) then
            perform public.rbo_dnevnik_zapisi(old.id_oprema, 'Slike', format('Odstranjena je bila %s.', ime));
        end if;
        return old;
    end if;
    return new;
end
$$;

drop trigger if exists rbo_dnevnik_slike on public.rbo_slike;
create trigger rbo_dnevnik_slike after insert or update or delete on public.rbo_slike
    for each row execute function public.rbo_dnevnik_slike();

-- 8d) Tehnični list
create or replace function public.rbo_dnevnik_tehnicni_list()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    r jsonb;
begin
    if tg_op = 'INSERT' then
        perform public.rbo_dnevnik_zapisi(new.id_oprema, 'Tehnični list', 'Tehnični list je bil ustvarjen.');
        return new;
    end if;
    if old.visible and not new.visible then
        perform public.rbo_dnevnik_zapisi(new.id_oprema, 'Tehnični list', 'Tehnični list je bil izbrisan.');
        return new;
    end if;
    if not old.visible and new.visible then
        perform public.rbo_dnevnik_zapisi(new.id_oprema, 'Tehnični list', 'Tehnični list je bil ponovno ustvarjen.');
    end if;
    r := public.rbo_dnevnik_razlike('rbo_tehnicni_list', to_jsonb(old), to_jsonb(new));
    if jsonb_array_length(r) > 0 then
        perform public.rbo_dnevnik_zapisi(new.id_oprema, 'Tehnični list',
            'Tehnični list: ' || replace(public.rbo_dnevnik_besedilo(r), E'\n', E'\nTehnični list: '), r);
    end if;
    return new;
end
$$;

drop trigger if exists rbo_dnevnik_tehnicni_list on public.rbo_tehnicni_list;
create trigger rbo_dnevnik_tehnicni_list after insert or update on public.rbo_tehnicni_list
    for each row execute function public.rbo_dnevnik_tehnicni_list();

-- 8e) Kartoteka: izbris ročnega zapisa
create or replace function public.rbo_dnevnik_kartoteka()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if old.visible and not new.visible then
        perform public.rbo_dnevnik_zapisi(new.id_oprema, 'Kartoteka',
            format('Izbrisan je bil ročni zapis z dne %s: »%s«', to_char(old.datum_vnosa, 'DD.MM.YYYY'),
                   left(old.besedilo_vnosa, 200) || case when length(old.besedilo_vnosa) > 200 then ' ...' else '' end));
    end if;
    return new;
end
$$;

drop trigger if exists rbo_dnevnik_kartoteka on public.rbo_kartoteka;
create trigger rbo_dnevnik_kartoteka after update on public.rbo_kartoteka
    for each row execute function public.rbo_dnevnik_kartoteka();

-- 9) Začetni zapis za opremo, ki je bila v sistemu že pred dnevnikom (samo enkrat)
insert into public.rbo_dnevnik (id_oprema, sklop, besedilo)
select o.id, 'Oprema',
       'Začetek beleženja sprememb. Oprema je bila v sistem dodana že prej'
       || coalesce(' (datum prejema: ' || to_char(o.datum_prejema, 'DD.MM.YYYY') || ')', '') || '.'
from public.rbo_oprema o
where not exists (select 1 from public.rbo_dnevnik d where d.id_oprema = o.id);

-- 10) Pogled: dodan stolpec kupec (na koncu, da create or replace deluje)
create or replace view public.v_rbo_oprema_prodaja
with (security_invoker = true) as
select
    o.id                      as id_oprema,
    o.datum_prejema,
    ps.ime_slike              as predstavna_slika,
    o.kolicina,
    o.em,
    o.koda,
    o.serijska_stevilka,
    o.leto_proizvodnje,
    o.skupina_opreme,
    o.oprema_naziv,
    o.lastnistvo,
    o.skladisce,
    o.komentar,
    o.ocena,
    p.id_prodaja,
    p.imenovani_prodajalec,
    p.garancijski_rok_meseci,
    p.cena_nove,
    p.rabat_procent,
    p.prodajna_cena,
    p.datum_prodaje,
    p.komentar_ob_prodaji,
    p.status_prodaje,
    exists (select 1 from public.rbo_tehnicni_list tl where tl.id_oprema = o.id and tl.visible) as ima_tehnicni_list,
    exists (select 1 from public.rbo_kartoteka k where k.id_oprema = o.id and k.visible) as ima_kartoteko,
    p.kupec
from public.rbo_oprema o
left join public.rbo_slike ps on ps.id_oprema = o.id and ps.vrsta_slike = 'Predstavna'
left join lateral (
    select pr.*
    from public.ln_rbo_oprema_prodaja po
    join public.rbo_prodaja pr on pr.id_prodaja = po.id_prodaja
    where po.id_oprema = o.id and pr.visible
    order by pr.id_prodaja desc
    limit 1
) p on true
where o.visible;

-- 11) Uskladitev s standardom (podatkov se ne briše; brisanje dovoljeno samo za slike)
--     ln_rbo_oprema_prodaja: brez pravila za brisanje (aplikacija povezav ne briše)
drop policy if exists "fines izbrisi" on public.ln_rbo_oprema_prodaja;

--     šifranti: namesto "for all" (vključuje brisanje) samo dodajanje in urejanje; branje ostane "fines beri"
do $$
declare
    t text;
begin
    foreach t in array array['rbo_sif_skupina_opreme', 'rbo_sif_lastnistvo', 'rbo_sif_skladisce', 'rbo_sif_prodajalec'] loop
        execute format('drop policy if exists "fines uredi" on public.%I', t);
        execute format('drop policy if exists "fines dodaj" on public.%I', t);
        execute format('create policy "fines dodaj" on public.%I for insert to authenticated with check (public.rbo_lahko_ureja())', t);
        execute format('create policy "fines uredi" on public.%I for update to authenticated using (public.rbo_lahko_ureja()) with check (public.rbo_lahko_ureja())', t);
    end loop;
end $$;
